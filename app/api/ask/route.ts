// ─── مساعد: استخرج JSON من نص قد يحتوي على markdown ```json ─────────────
function extractJson(text: string): string {
  const match = text.match(/```(?:json)?\s*([\s\S]*?)```/);
  return match ? match[1].trim() : text.trim();
}

